-- ---------------------------------------------------------------------
-- Limpeza (ordem inversa das dependências)
-- ---------------------------------------------------------------------
BEGIN
    FOR t IN (SELECT table_name
                FROM user_tables
               WHERE table_name IN ('NOTIFICACAO', 'AUDITORIA', 'LEITURA',
                                    'AVALIACAO_RISCO', 'DISPOSITIVO',
                                    'USUARIO', 'BAIRRO'))
    LOOP
        EXECUTE IMMEDIATE 'DROP TABLE ' || t.table_name || ' CASCADE CONSTRAINTS PURGE';
    END LOOP;
END;
/

-- ---------------------------------------------------------------------
-- BAIRRO: território monitorado (código IBGE do município)
-- ---------------------------------------------------------------------
CREATE TABLE BAIRRO (
    ID                 NUMBER GENERATED BY DEFAULT AS IDENTITY,
    NOME               VARCHAR2(120)  NOT NULL,
    MUNICIPIO          VARCHAR2(120)  NOT NULL,
    UF                 CHAR(2)        NOT NULL,
    CODIGO_IBGE        VARCHAR2(7)    NOT NULL,
    AGUA_INTERMITENTE  CHAR(1)        DEFAULT 'N' NOT NULL,
    NIVEL_RISCO        VARCHAR2(10)   DEFAULT 'VERDE' NOT NULL,
    CONSTRAINT PK_BAIRRO PRIMARY KEY (ID),
    CONSTRAINT UK_BAIRRO_NOME_IBGE UNIQUE (NOME, CODIGO_IBGE),
    CONSTRAINT CK_BAIRRO_AGUA CHECK (AGUA_INTERMITENTE IN ('S', 'N')),
    CONSTRAINT CK_BAIRRO_NIVEL CHECK (NIVEL_RISCO IN ('VERDE', 'AMARELO', 'LARANJA', 'VERMELHO')),
    CONSTRAINT CK_BAIRRO_IBGE CHECK (REGEXP_LIKE(CODIGO_IBGE, '^[0-9]{7}$'))
);

-- ---------------------------------------------------------------------
-- USUARIO: cidadão (morador) ou gestor da vigilância em saúde
-- LGPD: apenas nome, e-mail e bairro.
-- ---------------------------------------------------------------------
CREATE TABLE USUARIO (
    ID          NUMBER GENERATED BY DEFAULT AS IDENTITY,
    NOME        VARCHAR2(120)  NOT NULL,
    EMAIL       VARCHAR2(160)  NOT NULL,
    SENHA_HASH  VARCHAR2(100)  NOT NULL,
    PAPEL       VARCHAR2(10)   NOT NULL,
    BAIRRO_ID   NUMBER,
    CRIADO_EM   TIMESTAMP      DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT PK_USUARIO PRIMARY KEY (ID),
    CONSTRAINT UK_USUARIO_EMAIL UNIQUE (EMAIL),
    CONSTRAINT CK_USUARIO_PAPEL CHECK (PAPEL IN ('CIDADAO', 'GESTOR')),
    CONSTRAINT FK_USUARIO_BAIRRO FOREIGN KEY (BAIRRO_ID) REFERENCES BAIRRO (ID)
);

-- ---------------------------------------------------------------------
-- DISPOSITIVO: aparelho Ressoa instalado num recipiente de água
-- ---------------------------------------------------------------------
CREATE TABLE DISPOSITIVO (
    ID               NUMBER GENERATED BY DEFAULT AS IDENTITY,
    NUMERO_SERIE     VARCHAR2(40)   NOT NULL,
    USUARIO_ID       NUMBER         NOT NULL,
    BAIRRO_ID        NUMBER         NOT NULL,
    TIPO_RECIPIENTE  VARCHAR2(12)   NOT NULL,
    VOLUME_LITROS    NUMBER(6)      NOT NULL,
    PULSOS_POR_DIA   NUMBER(2)      DEFAULT 1 NOT NULL,
    STATUS           VARCHAR2(15)   DEFAULT 'ATIVO' NOT NULL,
    INSTALADO_EM     TIMESTAMP      DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT PK_DISPOSITIVO PRIMARY KEY (ID),
    CONSTRAINT UK_DISPOSITIVO_SERIE UNIQUE (NUMERO_SERIE),
    CONSTRAINT CK_DISPOSITIVO_TIPO CHECK (TIPO_RECIPIENTE IN ('BALDE', 'TAMBOR', 'CAIXA_DAGUA')),
    CONSTRAINT CK_DISPOSITIVO_STATUS CHECK (STATUS IN ('ATIVO', 'SEM_SINAL', 'BATERIA_BAIXA', 'INATIVO')),
    CONSTRAINT CK_DISPOSITIVO_VOLUME CHECK (VOLUME_LITROS BETWEEN 1 AND 20000),
    CONSTRAINT CK_DISPOSITIVO_PULSOS CHECK (PULSOS_POR_DIA BETWEEN 1 AND 24),
    CONSTRAINT FK_DISPOSITIVO_USUARIO FOREIGN KEY (USUARIO_ID) REFERENCES USUARIO (ID),
    CONSTRAINT FK_DISPOSITIVO_BAIRRO FOREIGN KEY (BAIRRO_ID) REFERENCES BAIRRO (ID)
);

-- ---------------------------------------------------------------------
-- LEITURA: telemetria enviada pelo aparelho (API .NET)
-- CHAVE_IDEMPOTENCIA única garante que reenvios não dupliquem.
-- ---------------------------------------------------------------------
CREATE TABLE LEITURA (
    ID                  NUMBER GENERATED BY DEFAULT AS IDENTITY,
    DISPOSITIVO_ID      NUMBER         NOT NULL,
    CHAVE_IDEMPOTENCIA  VARCHAR2(64)   NOT NULL,
    REGISTRADA_EM       TIMESTAMP      DEFAULT SYSTIMESTAMP NOT NULL,
    BATERIA_PCT         NUMBER(3)      NOT NULL,
    TEMPERATURA_AGUA    NUMBER(4, 1)   NOT NULL,
    PULSO_OK            CHAR(1)        NOT NULL,
    CONSTRAINT PK_LEITURA PRIMARY KEY (ID),
    CONSTRAINT UK_LEITURA_CHAVE UNIQUE (CHAVE_IDEMPOTENCIA),
    CONSTRAINT CK_LEITURA_BATERIA CHECK (BATERIA_PCT BETWEEN 0 AND 100),
    CONSTRAINT CK_LEITURA_TEMP CHECK (TEMPERATURA_AGUA BETWEEN -10 AND 60),
    CONSTRAINT CK_LEITURA_PULSO CHECK (PULSO_OK IN ('S', 'N')),
    CONSTRAINT FK_LEITURA_DISPOSITIVO FOREIGN KEY (DISPOSITIVO_ID) REFERENCES DISPOSITIVO (ID) ON DELETE CASCADE
);

-- ---------------------------------------------------------------------
-- AVALIACAO_RISCO: nível de risco semanal por bairro (serviço de IA / gestor)
-- ---------------------------------------------------------------------
CREATE TABLE AVALIACAO_RISCO (
    ID                     NUMBER GENERATED BY DEFAULT AS IDENTITY,
    BAIRRO_ID              NUMBER         NOT NULL,
    SEMANA_EPIDEMIOLOGICA  NUMBER(6)      NOT NULL,
    NIVEL                  VARCHAR2(10)   NOT NULL,
    TEMP_MIN_MEDIA         NUMBER(4, 1),
    CASOS_100K             NUMBER(8, 2),
    RT                     NUMBER(5, 2),
    ORIENTACAO_IA          CLOB,
    CRIADA_EM              TIMESTAMP      DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT PK_AVALIACAO_RISCO PRIMARY KEY (ID),
    CONSTRAINT CK_AVALIACAO_NIVEL CHECK (NIVEL IN ('VERDE', 'AMARELO', 'LARANJA', 'VERMELHO')),
    CONSTRAINT CK_AVALIACAO_SEMANA CHECK (SEMANA_EPIDEMIOLOGICA BETWEEN 200001 AND 209953),
    CONSTRAINT FK_AVALIACAO_BAIRRO FOREIGN KEY (BAIRRO_ID) REFERENCES BAIRRO (ID) ON DELETE CASCADE
);

-- ---------------------------------------------------------------------
-- AUDITORIA: trilha alimentada por gatilhos (disciplina de Banco)
-- ---------------------------------------------------------------------
CREATE TABLE AUDITORIA (
    ID            NUMBER GENERATED BY DEFAULT AS IDENTITY,
    TABELA        VARCHAR2(30)   NOT NULL,
    OPERACAO      VARCHAR2(10)   NOT NULL,
    VALOR_ANTIGO  CLOB,
    VALOR_NOVO    CLOB,
    USUARIO_BD    VARCHAR2(128)  DEFAULT USER NOT NULL,
    DATA_HORA     TIMESTAMP      DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT PK_AUDITORIA PRIMARY KEY (ID),
    CONSTRAINT CK_AUDITORIA_OPERACAO CHECK (OPERACAO IN ('INSERT', 'UPDATE', 'DELETE'))
);

-- ---------------------------------------------------------------------
-- NOTIFICACAO: alerta ao morador quando o risco do bairro sobe
-- (gravada pelo consumidor RabbitMQ do evento risco.atualizado)
-- ---------------------------------------------------------------------
CREATE TABLE NOTIFICACAO (
    ID            NUMBER GENERATED BY DEFAULT AS IDENTITY,
    USUARIO_ID    NUMBER          NOT NULL,
    AVALIACAO_ID  NUMBER          NOT NULL,
    TITULO        VARCHAR2(120)   NOT NULL,
    MENSAGEM      VARCHAR2(1000)  NOT NULL,
    LIDA          CHAR(1)         DEFAULT 'N' NOT NULL,
    CRIADA_EM     TIMESTAMP       DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT PK_NOTIFICACAO PRIMARY KEY (ID),
    CONSTRAINT UK_NOTIFICACAO_USUARIO_AVALIACAO UNIQUE (USUARIO_ID, AVALIACAO_ID),
    CONSTRAINT CK_NOTIFICACAO_LIDA CHECK (LIDA IN ('S', 'N')),
    CONSTRAINT FK_NOTIFICACAO_USUARIO FOREIGN KEY (USUARIO_ID) REFERENCES USUARIO (ID) ON DELETE CASCADE,
    CONSTRAINT FK_NOTIFICACAO_AVALIACAO FOREIGN KEY (AVALIACAO_ID) REFERENCES AVALIACAO_RISCO (ID) ON DELETE CASCADE
);

-- ---------------------------------------------------------------------
-- Índices de apoio às consultas mais frequentes
-- ---------------------------------------------------------------------
CREATE INDEX IX_USUARIO_BAIRRO        ON USUARIO (BAIRRO_ID);
CREATE INDEX IX_DISPOSITIVO_USUARIO   ON DISPOSITIVO (USUARIO_ID);
CREATE INDEX IX_DISPOSITIVO_BAIRRO    ON DISPOSITIVO (BAIRRO_ID);
CREATE INDEX IX_LEITURA_DISP_DATA     ON LEITURA (DISPOSITIVO_ID, REGISTRADA_EM DESC);
CREATE INDEX IX_AVALIACAO_BAIRRO_SEM  ON AVALIACAO_RISCO (BAIRRO_ID, SEMANA_EPIDEMIOLOGICA DESC);
CREATE INDEX IX_NOTIFICACAO_USUARIO   ON NOTIFICACAO (USUARIO_ID, LIDA);

COMMENT ON TABLE BAIRRO          IS 'Bairros monitorados pelo Ressoa';
COMMENT ON TABLE USUARIO         IS 'Moradores (CIDADAO) e gestores de saúde (GESTOR)';
COMMENT ON TABLE DISPOSITIVO     IS 'Aparelhos Ressoa de ultrassom instalados em recipientes de água';
COMMENT ON TABLE LEITURA         IS 'Telemetria diária dos aparelhos (bateria, temperatura, pulso)';
COMMENT ON TABLE AVALIACAO_RISCO IS 'Nível de risco de dengue por bairro e semana epidemiológica';
COMMENT ON TABLE AUDITORIA       IS 'Trilha de auditoria preenchida por gatilhos';
COMMENT ON TABLE NOTIFICACAO     IS 'Alertas aos moradores quando o risco do bairro sobe';
